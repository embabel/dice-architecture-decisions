import { expect, test } from '@playwright/test'

test('explores a decision, asks natural questions and tests a hypothetical replay drill', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/')
  const graph = page.getByRole('region', { name: 'Decision graph nodes' })
  const inspector = page.getByRole('region', { name: 'Selected graph evidence' })
  const conversation = page.locator('#messages')
  const question = page.getByRole('textbox', { name: 'Ask about the decision' })
  const ask = page.getByRole('button', { name: 'Ask', exact: true })

  await expect(graph.getByRole('button')).toHaveCount(9)
  await expect(graph.locator('path')).toHaveCount(10)
  await graph.getByRole('button', { name: /Queue availability Updated evidence/ }).click()
  await expect(inspector).toContainText('Regional service matrix')
  await expect(inspector).toContainText('EU West queue deployment')

  await question.fill('What is stopping us from migrating to the queue?')
  await ask.click()
  await expect(conversation).toContainText('Migration review still needs evidence for Replay recovery.')
  await question.fill('What evidence is missing?')
  await ask.click()
  await expect(conversation.getByRole('button', { name: /Migration review/ })).toHaveCount(2)
  await conversation.getByRole('button', { name: /Migration review/ }).last().click()
  await expect(inspector).toBeFocused()
  await expect(inspector).toContainText('Unmet')
  await question.fill('Who discovered Neptune?')
  await ask.click()
  await expect(conversation).toContainText('Would you like to know what still blocks migration review?')

  await page.getByText('Assume a passing replay drill', { exact: true }).click()
  await expect(graph.getByRole('button', { name: /Migration review Ready in scenario/ })).toBeVisible()
  await expect(inspector).toContainText('Assumed passing replay drill')
  await expect(conversation).toBeEmpty()
  await expect(page.getByRole('button', { name: /Approved ADR/ })).toBeEnabled()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: /At adoption/ }).click()
  await expect(graph.getByRole('button', { name: /Migration review Blocked/ })).toBeVisible()
  await graph.getByRole('button', { name: /Queue availability Original evidence/ }).click()
  await expect(inspector).toContainText('Regional service matrix')
  await expect(inspector).not.toContainText('EU West queue deployment')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
